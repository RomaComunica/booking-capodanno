<?php

require __DIR__ . '/../vendor/autoload.php';
$app = require_once __DIR__ . '/../bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

use App\Models\EntrataUscita;
use App\Services\StatisticsService;
use Illuminate\Support\Facades\DB;

echo "=== STARTING FINANCIAL REPORT TEST ===\n\n";

try {
    $service = new StatisticsService();
    $year = date('Y');
    
    // 1. Get initial profit and cash flow stats
    echo "1. Fetching initial stats for year {$year}...\n";
    $initialStats = $service->getDashboardStats($year);
    $initialCashFlow = $service->getCashFlowStats($year);
    
    $initialProfit = $initialStats['total_profit'];
    $initialMargin = $initialStats['total_margin'];
    $initialEntrate = $initialCashFlow['entrate'];
    $initialUscite = $initialCashFlow['uscite'];
    
    echo "   Initial Margin:  € " . number_format($initialMargin, 2) . "\n";
    echo "   Initial Entrate: € " . number_format($initialEntrate, 2) . "\n";
    echo "   Initial Uscite:  € " . number_format($initialUscite, 2) . "\n";
    echo "   Initial Net Profit:  € " . number_format($initialProfit, 2) . "\n\n";
    
    // 2. Insert a test Entrata (Income)
    echo "2. Inserting test Entrata (+ €150.00)...\n";
    DB::beginTransaction();
    
    $entrata = EntrataUscita::create([
        'dataOperazione' => now()->format('Y-m-d'),
        'tipoOperazione' => 'E',
        'causale' => 'TEST ENTRATA EXTRA AGENT',
        'importo' => 150.00,
        'descrizione' => 'Test extra entry generated by Antigravity AI'
    ]);
    echo "   Saved record ID: {$entrata->idEntrataUscita}\n";
    
    // Fetch stats again with the new Entrata
    $afterEntrataStats = $service->getDashboardStats($year);
    $afterEntrataCashFlow = $service->getCashFlowStats($year);
    
    $afterEntrataProfit = $afterEntrataStats['total_profit'];
    $afterEntrataEntrate = $afterEntrataCashFlow['entrate'];
    
    echo "   New Entrate: € " . number_format($afterEntrataEntrate, 2) . "\n";
    echo "   New Net Profit: € " . number_format($afterEntrataProfit, 2) . "\n";
    
    $diffEntrate = $afterEntrataEntrate - $initialEntrate;
    $diffProfit1 = $afterEntrataProfit - $initialProfit;
    
    echo "   Diff Entrate: +€ " . number_format($diffEntrate, 2) . "\n";
    echo "   Diff Profit: +€ " . number_format($diffProfit1, 2) . "\n";
    
    if (abs($diffEntrate - 150.00) < 0.001 && abs($diffProfit1 - 150.00) < 0.001) {
        echo "   [SUCCESS] Entrata correctly saved and reflected in Net Profit!\n\n";
    } else {
        echo "   [FAILURE] Entrata did not reflect correctly!\n\n";
    }
    
    // 3. Insert a test Uscita (Expense)
    echo "3. Inserting test Uscita (- €50.00)...\n";
    $uscita = EntrataUscita::create([
        'dataOperazione' => now()->format('Y-m-d'),
        'tipoOperazione' => 'U',
        'causale' => 'TEST USCITA EXTRA AGENT',
        'importo' => 50.00,
        'descrizione' => 'Test extra expense generated by Antigravity AI'
    ]);
    echo "   Saved record ID: {$uscita->idEntrataUscita}\n";
    
    // Fetch stats again with the new Uscita
    $afterUscitaStats = $service->getDashboardStats($year);
    $afterUscitaCashFlow = $service->getCashFlowStats($year);
    
    $afterUscitaProfit = $afterUscitaStats['total_profit'];
    $afterUscitaUscite = $afterUscitaCashFlow['uscite'];
    
    echo "   New Uscite: € " . number_format($afterUscitaUscite, 2) . "\n";
    echo "   New Net Profit: € " . number_format($afterUscitaProfit, 2) . "\n";
    
    $diffUscite = $afterUscitaUscite - $initialUscite;
    $diffProfit2 = $afterUscitaProfit - $afterEntrataProfit;
    
    echo "   Diff Uscite: +€ " . number_format($diffUscite, 2) . "\n";
    echo "   Diff Profit: -€ " . number_format(-$diffProfit2, 2) . "\n";
    
    if (abs($diffUscite - 50.00) < 0.001 && abs($diffProfit2 - (-50.00)) < 0.001) {
        echo "   [SUCCESS] Uscita correctly saved and reflected in Net Profit!\n\n";
    } else {
        echo "   [FAILURE] Uscita did not reflect correctly!\n\n";
    }
    
    // Rollback so we don't pollute the database
    DB::rollBack();
    echo "4. Transaction rolled back successfully. Database remains clean.\n\n";
    echo "=== FINANCIAL REPORT TEST COMPLETED ===\n";
    
} catch (\Exception $e) {
    if (DB::transactionLevel() > 0) {
        DB::rollBack();
    }
    echo "=== ERROR OCCURRED ===\n";
    echo $e->getMessage() . "\n";
    echo $e->getTraceAsString() . "\n";
}
